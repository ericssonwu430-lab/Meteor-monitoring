/** First-order precession J2000/ICRF → B1875.0 (IAU 1976 / Newcomb). */
export function precessJ2000ToB1875(
  raHours: number,
  decDeg: number
): { raHours: number; decDeg: number } {
  const T = (1875.0 - 2000.0) / 100.0;
  const arcsec = Math.PI / (180 * 3600);
  const zeta =
    (2306.2181 * T + 0.30188 * T * T + 0.017998 * T * T * T) * arcsec;
  const z =
    (2306.2181 * T + 1.09468 * T * T + 0.018203 * T * T * T) * arcsec;
  const theta =
    (2004.3109 * T - 0.42665 * T * T - 0.041833 * T * T * T) * arcsec;

  const ra = raHours * 15 * (Math.PI / 180);
  const dec = decDeg * (Math.PI / 180);
  const cosD = Math.cos(dec);
  const sinD = Math.sin(dec);
  const A = cosD * Math.sin(ra + zeta);
  const B = Math.cos(theta) * cosD * Math.cos(ra + zeta) - Math.sin(theta) * sinD;
  const C = Math.sin(theta) * cosD * Math.cos(ra + zeta) + Math.cos(theta) * sinD;
  let ra2 = Math.atan2(A, B) + z;
  ra2 = ((ra2 % (2 * Math.PI)) + 2 * Math.PI) % (2 * Math.PI);
  const dec2 = Math.asin(Math.max(-1, Math.min(1, C)));
  return {
    raHours: (ra2 * 180) / Math.PI / 15,
    decDeg: (dec2 * 180) / Math.PI,
  };
}

export function constellationFromRaDec(
  raHours: number,
  decDeg: number
): ConstellationHit {
  const p = precessJ2000ToB1875(raHours, decDeg);
  const ra = ((p.raHours % 24) + 24) % 24;
  const dec = p.decDeg;
  for (const z of ZONES) {
    if (dec >= z.decLow && ra >= z.raLow && ra < z.raHigh) {
      return { abbr: z.abbr, name: IAU_NAMES[z.abbr] ?? z.abbr };
    }
  }
  return { abbr: "Oct", name: "Octans" };
}

export function constellationName(abbr: string): string {
  return IAU_NAMES[abbr] ?? abbr;
}
